import type { Books } from "@/lib/reportBundle";
import type { buildReports } from "@/lib/reportBundle";
import { formatINR } from "@/lib/accounting/money";
import type { StatementRow } from "@/lib/accounting/reports";

type Reports = ReturnType<typeof buildReports>;

function table(rows: StatementRow[]): string {
  const lines = ["| Code | Particulars | Amount (₹) |", "|---|---|---:|"];
  for (const r of rows) {
    const label = r.kind === "heading" ? `**${r.label}**` : r.kind === "total" || r.kind === "subtotal" ? `**${r.label}**` : r.label;
    const amt = r.amount ? (r.kind === "total" || r.kind === "subtotal" ? `**${formatINR(r.amount, { symbol: false })}**` : formatINR(r.amount, { symbol: false })) : "";
    lines.push(`| ${r.code ?? ""} | ${label} | ${amt} |`);
  }
  return lines.join("\n");
}

/** Human-readable statements for the submission folder (generated from the same engine output as the workbook). */
export function statementsMarkdown(books: Books, rep: Reports): string {
  const f = rep.financials, bs = f.balanceSheet;
  const tb = ["| Code | Account | Debit (₹) | Credit (₹) |", "|---|---|---:|---:|",
    ...f.trialBalance.rows.map((r) => `| ${r.code} | ${r.name} | ${r.debit.isZero() ? "" : formatINR(r.debit, { symbol: false })} | ${r.credit.isZero() ? "" : formatINR(r.credit, { symbol: false })} |`),
    `| | **TOTAL** | **${formatINR(f.trialBalance.totalDebit, { symbol: false })}** | **${formatINR(f.trialBalance.totalCredit, { symbol: false })}** |`,
    `| | Difference | ${formatINR(f.trialBalance.difference, { symbol: false })} | |`].join("\n");
  const checks = ["| ID | Check | Expected | Actual | Difference | Result |", "|---|---|---:|---:|---:|---|",
    ...rep.checks.map((c) => `| ${c.id} | ${c.name} | ${formatINR(c.expected, { symbol: false })} | ${formatINR(c.actual, { symbol: false })} | ${formatINR(c.difference, { symbol: false })} | ${c.passed ? "PASS" : "FAIL"} |`)].join("\n");
  return `# Meridian Retail Traders - Financial Statements

Period: **${rep.period.start} to ${rep.period.end}** | Currency: INR (₹) | Source transactions: ${books.sources.length} | Journal entries: ${books.posted.entries.length}

> Fictional educational data. Generated by the accounting engine (\`npm run generate:submission\`).

## Trial Balance as at ${rep.period.end}

${tb}

## Profit and Loss Statement

${table(f.profitAndLoss.rows)}

## Balance Sheet as at ${rep.period.end}

${table(bs.rows)}

**Balance Sheet difference (Assets - Liabilities - Equity): ₹${bs.difference.toFixed(2)}** - ${bs.balanced ? "PASS (balanced)" : "FAIL"}

## Accounting validation

${checks}
`;
}
